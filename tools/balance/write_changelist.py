"""Write docs/balance-changes.md: a readable list of every applied and skipped change."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
changes = json.loads((ROOT / 'features/balance/changes.json').read_text())
entries = json.loads((ROOT / 'eid/generated/descriptions.json').read_text(encoding='utf-8'))['entries']
names = {(e['category'], e['lookup_id']): e['name'] for e in entries}


def item(i):
    return names.get(('collectibles', int(i)), f'Item {i}')


def trinket(i):
    return names.get(('trinkets', int(i)), f'Trinket {i}')


lines = ['# Repentance+ balance changes in this build', '',
         'Generated by `tools/balance/write_changelist.py` from `features/balance/changes.json`.',
         'Values come from the PC Repentance+ v1.9.7.17 data; only data the Switch',
         'Repentance 1.7.9b game already reads was changed.', '',
         '## Item effects and prices', '', '| Item | Change |', '| --- | --- |']
seen = set()
for c in changes['items']:
    key = (c['id'], c['reason'])
    if key in seen:
        continue
    seen.add(key)
    lines.append(f"| {item(c['id'])} | {c['reason']} |")

quality = [c for c in changes['metadata'] if c['attribute'] == 'quality']
lines += ['', f'## Quality ratings ({len(quality)} items)', '',
          'Quality affects Bag of Crafting results, Sacred Orb rerolls, Tainted Lost\'s', 'item choices and the Specialist dance, as well as the rating shown in descriptions.', '',
          '| Item | Old | New |', '| --- | --- | --- |']
for c in sorted(quality, key=lambda c: item(c['id'])):
    lines.append(f"| {item(c['id'])} | {c['switch']} | {c['new']} |")

craft = [c for c in changes['metadata'] if c['attribute'] == 'craftquality']
lines += ['', f'## Bag of Crafting quality overrides ({len(craft)} items)', '', '| Item | Old | New |', '| --- | --- | --- |']
for c in sorted(craft, key=lambda c: item(c['id'])):
    lines.append(f"| {item(c['id'])} | {c['switch'] or 'none'} | {c['new'] or 'none'} |")

tags = [c for c in changes['metadata'] if c['attribute'] == 'tags']
lines += ['', f'## Tags ({len(tags)} items or trinkets)', '',
          'Tags decide transformations (baby = Conjoined, angel = Seraphim, ...), Monster',
          'Manual/Lemegeton choices, and Greed/challenge availability.', '',
          '| Item | Added | Removed |', '| --- | --- | --- |']
for c in sorted(tags, key=lambda c: (c['tag'], c['id'])):
    old, new = set((c['switch'] or '').split()), set((c['new'] or '').split())
    label = item(c['id']) if c['tag'] == 'item' else trinket(c['id']) + ' (trinket)'
    lines.append(f"| {label} | {' '.join(sorted(new - old)) or '-'} | {' '.join(sorted(old - new)) or '-'} |")

lines += ['', f"## Item pools ({len(changes['pools'])} edits)", '', '| Pool | Item | Change |', '| --- | --- | --- |']
for c in sorted(changes['pools'], key=lambda c: (c['pool'], item(c['id']))):
    if c['change'] == 'weights':
        detail = f"weight {c['switch'].get('Weight')} -> {c['pc'].get('Weight')}"
    elif c['change'] == 'added':
        detail = f"added (weight {c['pc'].get('Weight')})"
    else:
        detail = 'removed'
    lines.append(f"| {c['pool']} | {item(c['id'])} | {detail} |")

pocket_names = {('card', '72'): 'The Tower? (reversed card)', ('card', '84'): 'Soul of Judas',
                ('pilleffect', '21'): 'Hematemesis pill', ('pilleffect', '25'): 'Amnesia pill',
                ('pilleffect', '31'): '??? pill', ('rune', '38'): 'Berkano'}
lines += ['', '## Cards, runes and pills', '', '| Pocket item | Change |', '| --- | --- |']
for c in changes['pocket']:
    label = pocket_names.get((c['tag'], str(c['id'])), f"{c['tag']} {c['id']}")
    what = (f"Blank Card / Clear Rune / Placebo charge {c['switch']} -> {c['new']}" if c['attribute'] == 'mimiccharge'
            else 'No longer appears in Greed Mode')
    lines.append(f'| {label} | {what} |')

lines += ['', f"## Not applied ({len(changes['excluded'])})", '', '| What | Why |', '| --- | --- |']
for c in changes['excluded']:
    if 'pool' in c:
        what = f"{c['pool']} pool: {item(c['id'])}"
    elif c.get('dropped'):
        what = f"{item(c['id'])}: tag {', '.join(c['dropped'])}"
    else:
        label = item(c['id']) if c.get('tag') in ('active', 'passive', 'familiar', 'item') else trinket(c['id']) + ' (trinket)'
        what = f"{label}: {c['attribute']}"
    lines.append(f"| {what} | {c['reason']} |")
lines += ['', 'Also not applied: character starting items (Repentance+ moved them into code, so',
          'copying its players.xml would remove them on Switch), wisp, challenge and costume',
          'tweaks, and every behavior rework (Abyss, Delirious, Milk!, Dataminer, Mars, ...).', '']
(ROOT / 'docs/balance-changes.md').write_text('\n'.join(lines), encoding='utf-8')
print('wrote docs/balance-changes.md', len(lines), 'lines')
