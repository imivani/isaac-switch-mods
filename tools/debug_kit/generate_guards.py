"""Generate exact native-call guards and record the item IDs from this user's dump."""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
raw = (ROOT.parent / 'Isaac-dump/romfs/.nro/Repentance.nro').read_bytes()
expected = 'cc363208c220f65547edda6d8268b3b6c0f7373b14c91ae6ffb378018de4b66a'
assert hashlib.sha256(raw).hexdigest() == expected
symbols = json.loads((ROOT / 'evidence/native-analysis/symbols.json').read_text())
targets = {
    'IsButtonPressed': '_ZN4KAGE5Input11ManagerBase15IsButtonPressedEjjPj',
    'IsPaused': '_ZNK15IsaacRepentance4Game8IsPausedEv',
    'Spawn': '_ZN15IsaacRepentance4Game7SpawnExENS_11eEntityTypeEjRKN4KAGE4Math7Vector2ES6_PNS_6EntityEjjj',
    'FindPosition': '_ZNK15IsaacRepentance4Room27FindFreePickupSpawnPositionERKN4KAGE4Math7Vector2Efbb',
    'Milliseconds': '_ZN4KAGE6System4Time15GetMillisecondsEv',
    'GetCollectible': '_ZNK15IsaacRepentance10ItemConfig14GetCollectibleEi',
}
lines = ['// Generated by tools/debug_kit/generate_guards.py from the verified dump.', '#pragma once', '#include <cstdint>', 'namespace isaac::debug_kit::native {']
report = {'nro_sha256': expected, 'guards': {}, 'input_manager_got': '0xaac768', 'button_ids': {'left_stick_click':10,'right_stick_click':13,'dpad_down':3}}
for label, name in targets.items():
    entry = next(x for x in symbols if x['defined'] and x['name'] == name)
    offset, size = entry['offset'], entry['size']
    guard = raw[offset:offset + min(20,size)]
    lines += [f'inline constexpr std::uintptr_t {label} = 0x{offset:x};', f'inline constexpr std::uint8_t {label}Guard[] = {{' + ','.join(f'0x{x:02x}' for x in guard) + '};']
    report['guards'][label] = {'symbol':name, 'offset':hex(offset),'bytes':guard.hex()}
lines.append('}')
(ROOT/'native/source/program/generated/debug_kit_guards.hpp').write_text('\n'.join(lines)+'\n')
items = ET.parse(ROOT.parent/'Isaac-dump/romfs/resources/items.xml').getroot()
names = {int(e.attrib['id']):e.attrib['name'] for e in items if e.tag in ('active','passive','familiar') and 'id' in e.attrib}
expected_items = {118:'Brimstone',38:"Tammy's Head",182:'Sacred Heart',313:'Holy Mantle',223:'Pyromaniac',356:'Car Battery'}
assert all(names.get(i) == name for i,name in expected_items.items())
report['items'] = expected_items
out = ROOT/'evidence/debug_kit'; out.mkdir(parents=True,exist_ok=True)
(out/'guards.json').write_text(json.dumps(report,indent=2)+'\n')
print(f'Debug kit: {len(targets)} verified native calls; {len(expected_items)} item IDs verified')
