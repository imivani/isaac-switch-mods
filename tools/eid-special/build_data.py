#!/usr/bin/env python3
"""Import only the pinned EID salvage strings/maps and exact Switch quest tags."""
import ast
import hashlib
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET


PROJECT = Path(__file__).resolve().parents[2]
UPSTREAM = PROJECT / "reference/External-Item-Descriptions"
PIN = "8b59d00c6828e333294639ad2b2b6875eae821cb"


def quoted(value):
    return json.dumps(value, ensure_ascii=True)


def main():
    commit = subprocess.check_output(["git", "-C", str(UPSTREAM), "rev-parse", "HEAD"], text=True).strip()
    assert commit == PIN, "Unexpected upstream revision"
    for relative in ("descriptions/rep/en_us.lua", "descriptions/ab+/en_us.lua", "features/eid_data.lua"):
        expected = subprocess.check_output(["git", "-C", str(UPSTREAM), "show", f"{PIN}:{relative}"])
        assert (UPSTREAM / relative).read_bytes().replace(b"\r\n", b"\n") == expected.replace(b"\r\n", b"\n"), relative
    rep = UPSTREAM / "descriptions/rep/en_us.lua"
    base = UPSTREAM / "descriptions/ab+/en_us.lua"
    data = UPSTREAM / "features/eid_data.lua"
    metadata = PROJECT.parent / "Isaac-dump/romfs/rp_patch/resources/items_metadata.xml"
    sources = [rep, base, data, metadata]
    rep_text, base_text, data_text = [path.read_text(encoding="utf-8-sig") for path in sources[:3]]
    names = ["TaintedCainPedestalBase", "TaintedCainPedestalBaseBirthright", "TaintedCainPedestalGuaranteed",
             "TaintedCainPedestalBonus", "TaintedCainPedestalLuckyToe", "TaintedCainPedestalLuckyToeBirthright",
             "TaintedCainPedestalDaemonsTail"]
    scalar = {}
    for name in names:
        match = re.search(r"EID\.descriptions\[languageCode\]\." + name + r'\s*=\s*("(?:[^"\\]|\\.)*")', rep_text)
        assert match, name
        scalar[name] = ast.literal_eval(match.group(1))
    maps = {}
    for name in ["SalvageTrinkets", "SalvageRoomTypes"]:
        match = re.search(r"EID\." + name + r"\s*=\s*\{([^\n]+)\}", data_text)
        assert match, name
        maps[name] = [(int(key), value) for key, value in re.findall(r'\[(\d+)\]\s*=\s*"([\d.]+)"', match.group(1))]
        assert maps[name], name
    pickup_block = re.search(r"\.PickupNames\s*=\s*\{(.*?)\n\}", base_text, re.S).group(1)
    pickups = {key: re.sub(r"\{\{[^}]+\}\}\s*", "", ast.literal_eval(value))
               for key, value in re.findall(r'\["([\d.]+)"\]\s*=\s*("(?:[^"\\]|\\.)*")', pickup_block)}
    quest = sorted(int(item.attrib["id"]) for item in ET.parse(metadata).getroot()
                   if "quest" in item.attrib.get("tags", "").split())
    lines = ["// Generated by tools/eid-special/build_data.py; do not hand-edit.",
             "// Source attribution: eid/THIRD_PARTY_NOTICES.md and eid/UPSTREAM-CREDITS.md.",
             "#pragma once", "namespace isaac_eid_special::data {",
             "inline constexpr unsigned QuestItems[] = {" + ",".join(map(str, quest)) + "};"]
    lines += [f"inline constexpr char {key}[] = {quoted(value)};" for key, value in scalar.items()]
    lines += ["struct PickupRule { unsigned id; const char* name; bool vowel; unsigned card; };" ]
    for name, rows in maps.items():
        lines.append(f"inline constexpr PickupRule {name}[] = {{")
        for key, value in rows:
            # Card names are resolved through the same pinned native catalogue.
            card = 78 if value == "5.300.78" else 0
            assert value in pickups or card, value
            lines.append("    {" + f"{key}, {quoted(pickups.get(value, ''))}, {'true' if value == '5.10.4' else 'false'}, {card}" + "},")
        lines.append("};")
    lines += ["} // namespace isaac_eid_special::data", ""]
    output = PROJECT / "eid_special/generated.hpp"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    report = {"upstream_commit": commit, "quest_items": quest,
              "source_sha256": {str(path.relative_to(PROJECT.parent)): hashlib.sha256(path.read_bytes()).hexdigest() for path in sources},
              "output_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
              "executed_lua": False}
    (output.parent / "data-build.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"PASS: imported {len(scalar)} source strings, {sum(map(len, maps.values()))} rules and {len(quest)} native quest tags")


if __name__ == "__main__":
    main()
