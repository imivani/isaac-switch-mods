"""Extract Instant Fires and Poops guards from the immutable Switch NRO."""
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'evidence/instant_break'
OUT.mkdir(parents=True, exist_ok=True)
SOURCE = Path(r'C:\Program Files (x86)\Steam\steamapps\workshop\content\250900\2833146105')
NRO = ROOT.parent / 'Isaac-dump/romfs/.nro/Repentance.nro'
EXPECTED = 'cc363208c220f65547edda6d8268b3b6c0f7373b14c91ae6ffb378018de4b66a'
raw = NRO.read_bytes()
assert hashlib.sha256(raw).hexdigest() == EXPECTED
symbols = json.loads((ROOT / 'evidence/native-analysis/symbols.json').read_text())
by_name = {x['name']: x for x in symbols if x['defined']}
targets = {
    'NpcTakeDamage': ('_ZN15IsaacRepentance10Entity_NPC10TakeDamageEfmRKNS_6Entity9EntityRefEi', 20),
    'NpcKill': ('_ZN15IsaacRepentance10Entity_NPC4KillEv', 20),
    'GridDestroy': ('_ZN15IsaacRepentance10GridEntity7DestroyEb', 16),
    'PoopHurt': ('_ZN15IsaacRepentance15GridEntity_Poop4HurtEi', 20),
    'RoomGridGetter': ('_ZNK15IsaacRepentance4Room13GetGridEntityEii', 20),
    'RoomTriggerClear': ('_ZN15IsaacRepentance4Room12TriggerClearEb', 20),
}
lines = ['// Generated by tools/instant_break/generate.py from the exact user dump.',
         '#pragma once', '#include <cstdint>', 'namespace isaac::instant_break::native {']
report = {'nro_sha256': EXPECTED, 'build_id': raw[0x40:0x60].hex(), 'guards': {}}
for label, (name, length) in targets.items():
    symbol = by_name[name]
    offset = symbol['offset']
    data = raw[offset:offset + length]
    assert len(data) == length and length <= symbol['size']
    lines.append(f'inline constexpr std::uintptr_t {label} = 0x{offset:x};')
    lines.append(f'inline constexpr std::uint8_t {label}Guard[] = {{' + ','.join(f'0x{x:02x}' for x in data) + '};')
    report['guards'][label] = {'symbol': name, 'offset': hex(offset), 'size': symbol['size'], 'bytes': data.hex()}

# Confirm the real virtual dispatch used by GridEntity::Destroy, rather than
# relying on a class-name or a guessed C++ object layout.
mod0 = struct.unpack_from('<I', raw, 4)[0]
dynamic = mod0 + struct.unpack_from('<i', raw, mod0 + 4)[0]
tags = {}
for position in range(dynamic, len(raw), 16):
    tag, value = struct.unpack_from('<qQ', raw, position)
    if not tag:
        break
    tags[tag] = value
relocations = {}
for position in range(tags[7], tags[7] + tags[8], 24):
    offset, info, addend = struct.unpack_from('<QQq', raw, position)
    relocations[offset] = (info, addend)
vtable = by_name['_ZTVN15IsaacRepentance15GridEntity_PoopE']['offset'] + 16
info, addend = relocations[vtable + 0x28]
index = info >> 32
target = symbols[index]['offset'] + addend if index else addend
assert target == by_name[targets['PoopHurt'][0]]['offset']
lines.append(f'inline constexpr std::uintptr_t PoopVtable = 0x{vtable:x};')
lines.append(f'inline constexpr std::uintptr_t GameGlobal = 0x{by_name["_ZN15IsaacRepentance6g_GameE"]["offset"]:x};')
lines.append('}')
report['poop_vtable'] = {'address_point': hex(vtable), 'hurt_slot': '0x28', 'resolved_target': hex(target)}
destination = ROOT / 'features/instant_break/native_profile.hpp'
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text('\n'.join(lines) + '\n')
(OUT / 'guards.json').write_text(json.dumps(report, indent=2) + '\n')
provenance = {
    'workshop_id': '2833146105', 'name': 'Instant Fires and Poops', 'version': '1.1',
    'source_files': {name: {'path': str(SOURCE / name), 'sha256': hashlib.sha256((SOURCE / name).read_bytes()).hexdigest()}
                     for name in ('main.lua', 'metadata.xml')},
    'observed_source_behavior': ['Only fireplace type33 variant0 on damage while room clear',
        'Poop state increase triggers native Destroy on post-update while clear',
        'Poop baselines update while room is not clear and reset on room entry'],
    'adaptation': ['Keep native damage attribution, then kill an orange fire after an accepted positive damage event',
        'Call native GridEntity::Destroy, preserving native drops, effects, and giant-poop forwarding',
        'Reset baselines when a grid object is replaced or regenerated to avoid stale state destroying a new object'],
    'hardware_test': False,
}
(OUT / 'provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
print(f'Instant break: {len(targets)} exact guards and poop virtual dispatch verified')
