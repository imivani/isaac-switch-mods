"""Exact-build guards for every game function the mod menu calls or hooks.

Also records the game's own file-system import stubs (and the pointer slots
they jump through) so settings can be saved with the game's already-resolved
functions: no new SDK imports are added to the add-on.
Writes native/source/program/generated/menu_guards.hpp and evidence/menu/guards.json.
"""
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXPECTED = 'cc363208c220f65547edda6d8268b3b6c0f7373b14c91ae6ffb378018de4b66a'
raw = (ROOT.parent / 'Isaac-dump/romfs/.nro/Repentance.nro').read_bytes()
assert hashlib.sha256(raw).hexdigest() == EXPECTED
symbols = json.loads((ROOT / 'evidence/native-analysis/symbols.json').read_text())
plt = json.loads((ROOT / 'evidence/native-analysis/plt.json').read_text())

FUNCTIONS = {
    'PauseProcessInput': '_ZN15IsaacRepentance11PauseScreen12ProcessInputEv',
    'PauseRender': '_ZN15IsaacRepentance11PauseScreen6RenderEv',
    'PlaySound': '_ZN15IsaacRepentance7Manager9PlaySoundENS_12eSoundEffectEfibf',
    'Seed2String': '_ZN15IsaacRepentance5Seeds11Seed2StringEj',
    'AddCollectible': '_ZN15IsaacRepentance13Entity_Player14AddCollectibleENS_16eCollectibleTypeEibii',
    'AddTrinket': '_ZN15IsaacRepentance13Entity_Player10AddTrinketENS_12eTrinketTypeEb',
    'AddCard': '_ZN15IsaacRepentance13Entity_Player7AddCardENS_5eCardE',
    'AddPill': '_ZN15IsaacRepentance13Entity_Player7AddPillENS_10ePillColorE',
    'AddCoins': '_ZN15IsaacRepentance13Entity_Player8AddCoinsEi',
    'AddBombs': '_ZN15IsaacRepentance13Entity_Player8AddBombsEi',
    'AddKeys': '_ZN15IsaacRepentance13Entity_Player7AddKeysEi',
    'AddSoulHearts': '_ZN15IsaacRepentance13Entity_Player13AddSoulHeartsEi',
    'SetFullHearts': '_ZN15IsaacRepentance13Entity_Player13SetFullHeartsEv',
    'FullCharge': '_ZN15IsaacRepentance13Entity_Player10FullChargeEib',
    'UseActiveItem': '_ZN15IsaacRepentance13Entity_Player13UseActiveItemENS_16eCollectibleTypeEjii',
    'HasCollectible': '_ZNK15IsaacRepentance13Entity_Player14HasCollectibleENS_16eCollectibleTypeEb',
    'ForceAddPillEffect': '_ZN15IsaacRepentance8ItemPool18ForceAddPillEffectENS_11ePillEffectE',
    'MakeShopItem': '_ZN15IsaacRepentance13Entity_Pickup12MakeShopItemEi',
    'ApplyMapEffect': '_ZN15IsaacRepentance5Level14ApplyMapEffectEv',
    'ApplyBlueMapEffect': '_ZN15IsaacRepentance5Level18ApplyBlueMapEffectEv',
    'ApplyCompassEffect': '_ZN15IsaacRepentance5Level18ApplyCompassEffectEb',
    'IsGreedMode': '_ZNK15IsaacRepentance4Game11IsGreedModeEv',
    'GetTrinket': '_ZNK15IsaacRepentance10ItemConfig10GetTrinketEi',
}
FS = {  # game import stub -> SDK function
    'FsOpenFile': '_ZN2nn2fs8OpenFileEPNS0_10FileHandleEPKci',
    'FsCloseFile': '_ZN2nn2fs9CloseFileENS0_10FileHandleE',
    'FsFlushFile': '_ZN2nn2fs9FlushFileENS0_10FileHandleE',
    'FsGetFileSize': '_ZN2nn2fs11GetFileSizeEPlNS0_10FileHandleE',
    'FsReadFile': '_ZN2nn2fs8ReadFileEPmNS0_10FileHandleElPvm',
    'FsWriteFile': '_ZN2nn2fs9WriteFileENS0_10FileHandleElPKvmRKNS0_11WriteOptionE',
    'FsSetFileSize': '_ZN2nn2fs11SetFileSizeENS0_10FileHandleEl',
    'FsCreateFile': '_ZN2nn2fs10CreateFileEPKcl',
    'FsIsMounted': '_ZN2nn2fs9IsMountedEPKc',
    'FsCommitSaveData': '_ZN2nn2fs14CommitSaveDataEPKc',
}
DATA = {
    'PauseScreenOffset': 0x1ae128,   # Game::Render -> PauseScreen::Render(game + 0x1ae128)
    'ItemPoolOffset': 0x242c0,       # Entity_Slot::Update -> ItemPool at game + 0x242c0
    'PlayerHistoryBegin': 0x24d0,    # PauseScreen::ProcessInput: 0x1c-byte history entries
    'PlayerType': 0x1738,
    'SaveMountString': 0x8927e3,     # SaveDataManager::GetMountPoint -> "sdmc:/"
}


def symbol(name):
    entry = next(x for x in symbols if x['defined'] and x['name'] == name)
    return entry['offset'], entry['size']


def main():
    lines = ['// Generated by tools/menu_ui/generate_guards.py from the verified dump.', '#pragma once', '#include <cstdint>',
             'namespace isaac::menu_native {']
    report = {'nro_sha256': EXPECTED, 'functions': {}, 'fs': {}, 'data': {}}
    for label, name in FUNCTIONS.items():
        offset, size = symbol(name)
        guard = raw[offset:offset + min(20, size)]
        assert len(guard) >= 8
        lines.append(f'inline constexpr std::uintptr_t {label} = 0x{offset:x};')
        lines.append(f'inline constexpr std::uint8_t {label}Guard[] = {{' + ','.join(f'0x{b:02x}' for b in guard) + '};')
        report['functions'][label] = {'symbol': name, 'offset': hex(offset), 'bytes': guard.hex()}
    for label, name in FS.items():
        stub = next(p for p in plt if p['symbol']['name'] == name)
        offset, got = stub['offset'], stub['got']
        adrp, ldr, add, br = struct.unpack_from('<4I', raw, offset)
        assert br == 0xd61f0220 and ldr & 0xffc003ff == 0xf9400211, label
        guard = raw[offset:offset + 16]
        lines.append(f'inline constexpr std::uintptr_t {label}Stub = 0x{offset:x}, {label}Slot = 0x{got:x};')
        lines.append(f'inline constexpr std::uint8_t {label}Guard[] = {{' + ','.join(f'0x{b:02x}' for b in guard) + '};')
        report['fs'][label] = {'symbol': name, 'stub': hex(offset), 'got': hex(got), 'bytes': guard.hex()}
    assert raw[DATA['SaveMountString']:DATA['SaveMountString'] + 7] == b'sdmc:/\0'
    for label, value in DATA.items():
        lines.append(f'inline constexpr std::uintptr_t {label} = 0x{value:x};')
        report['data'][label] = hex(value)
    lines.append('inline constexpr char SaveMount[] = "sdmc";')
    lines.append('inline constexpr char SaveFile[] = "sdmc:/isaac_mods_menu.cfg";')
    lines.append('}')
    (ROOT / 'native/source/program/generated/menu_guards.hpp').write_text('\n'.join(lines) + '\n')
    (ROOT / 'evidence/menu/guards.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f"Menu guards: {len(FUNCTIONS)} functions, {len(FS)} file-system stubs")


if __name__ == '__main__':
    main()
